-- 06_migracion_final.sql
--
-- Agrega el mapa de sillas, las boletas, la clave de idempotencia y los
-- triggers de coherencia. Se corre después de 01 a 05.
--
-- Nota: ventas.estado se mantiene en 'Pagada' / 'Anulada'. Las boletas de una
-- venta anulada quedan con estado 'Anulada' (historial) y su silla vuelve a
-- estar libre, porque el índice único solo considera las 'Valida'.

SET client_encoding = 'UTF8';

BEGIN;

-- ---------------------------------------------------------------------
-- 0. Limpieza
-- ---------------------------------------------------------------------
DROP VIEW  IF EXISTS v_estado_asientos CASCADE;
DROP TABLE IF EXISTS boletas  CASCADE;
DROP TABLE IF EXISTS asientos CASCADE;


-- ---------------------------------------------------------------------
-- 1. ASIENTOS: mapa de sillas
-- 10 sillas por fila (A, B, C...). Las salas suman 780 sillas, como la
-- capacidad declarada: 150 + 150 + 120 + 60 + 220 + 80.
-- tipo: 'VIP' en la sala VIP, 'Estandar' en las demás.
-- estado: 'Activo' (se puede vender) o 'Bloqueado' (dañada o en mantenimiento).
-- ---------------------------------------------------------------------
CREATE TABLE asientos (
    id_asiento INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    id_sala    INTEGER     NOT NULL,
    fila       VARCHAR(2)  NOT NULL,
    numero     INTEGER     NOT NULL,
    tipo       VARCHAR(10) NOT NULL DEFAULT 'Estandar',
    estado     VARCHAR(10) NOT NULL DEFAULT 'Activo',
    CONSTRAINT pk_asientos        PRIMARY KEY (id_asiento),
    CONSTRAINT fk_asientos_sala   FOREIGN KEY (id_sala)
        REFERENCES salas (id_sala) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_asientos_sala_fila_num UNIQUE (id_sala, fila, numero),
    CONSTRAINT ck_asientos_numero CHECK (numero BETWEEN 1 AND 50),
    CONSTRAINT ck_asientos_tipo   CHECK (tipo IN ('Estandar', 'VIP')),
    CONSTRAINT ck_asientos_estado CHECK (estado IN ('Activo', 'Bloqueado'))
);

INSERT INTO asientos (id_sala, fila, numero, tipo)
SELECT s.id_sala,
       CHR(64 + ((n - 1) / 10) + 1),
       ((n - 1) % 10) + 1,
       CASE WHEN s.tipo_sala = 'VIP' THEN 'VIP' ELSE 'Estandar' END
FROM salas s
CROSS JOIN LATERAL generate_series(1, s.capacidad) AS n
ORDER BY s.id_sala, n;

CREATE INDEX idx_asientos_sala ON asientos (id_sala);

COMMENT ON TABLE asientos IS 'Mapa de sillas de cada sala; la suma por sala coincide con salas.capacidad';


-- ---------------------------------------------------------------------
-- 2. BOLETAS: una fila por silla vendida
-- id_funcion se repite aquí (ya está en la venta) a propósito: permite el
-- índice único (función, silla), la garantía real contra vender dos veces
-- la misma silla. El trigger de abajo verifica que coincida con la venta.
-- ---------------------------------------------------------------------
CREATE TABLE boletas (
    id_boleta  INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    id_venta   INTEGER     NOT NULL,
    id_funcion INTEGER     NOT NULL,
    id_asiento INTEGER     NOT NULL,
    estado     VARCHAR(10) NOT NULL DEFAULT 'Valida',
    CONSTRAINT pk_boletas         PRIMARY KEY (id_boleta),
    CONSTRAINT fk_boletas_venta   FOREIGN KEY (id_venta)
        REFERENCES ventas (id_venta) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_boletas_funcion FOREIGN KEY (id_funcion)
        REFERENCES funciones (id_funcion) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_boletas_asiento FOREIGN KEY (id_asiento)
        REFERENCES asientos (id_asiento) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_boletas_estado  CHECK (estado IN ('Valida', 'Anulada'))
);

-- La misma silla no puede estar en dos boletas válidas de la misma función.
CREATE UNIQUE INDEX uq_boletas_funcion_asiento
    ON boletas (id_funcion, id_asiento) WHERE estado = 'Valida';

CREATE INDEX idx_boletas_venta   ON boletas (id_venta);
CREATE INDEX idx_boletas_asiento ON boletas (id_asiento);

COMMENT ON TABLE boletas IS 'Silla concreta de cada boleta vendida; unica por (funcion, silla) mientras la boleta este vigente';


-- ---------------------------------------------------------------------
-- 3. IDEMPOTENCY_KEY en ventas
-- El cliente manda un identificador por intento de compra; si llega el
-- mismo otra vez, la base lo rechaza (UNIQUE) y la API devuelve la venta
-- original. Es NULL en las ventas del Avance 1 (varios NULL no chocan).
-- ---------------------------------------------------------------------
ALTER TABLE ventas ADD COLUMN IF NOT EXISTS idempotency_key VARCHAR(64);
ALTER TABLE ventas DROP CONSTRAINT IF EXISTS uq_ventas_idempotency_key;
ALTER TABLE ventas ADD CONSTRAINT uq_ventas_idempotency_key UNIQUE (idempotency_key);


-- ---------------------------------------------------------------------
-- 4. BOLETAS PARA LAS VENTAS VIEJAS
-- Cada venta pagada del Avance 1 recibe sus sillas: dentro de cada función
-- se reparten en orden de venta, ocupando las primeras sillas de la sala.
-- Las ventas anuladas no reciben boletas.
-- ---------------------------------------------------------------------
WITH pagadas AS (
    SELECT v.id_venta, v.id_funcion, f.id_sala, v.cantidad,
           SUM(v.cantidad) OVER (PARTITION BY v.id_funcion ORDER BY v.id_venta) - v.cantidad AS desplazamiento
    FROM ventas v
    JOIN funciones f ON f.id_funcion = v.id_funcion
    WHERE v.estado = 'Pagada'
),
pedidas AS (
    SELECT p.id_venta, p.id_funcion, p.id_sala, p.desplazamiento + g AS pos
    FROM pagadas p
    CROSS JOIN LATERAL generate_series(1, p.cantidad) AS g
),
sillas AS (
    SELECT id_asiento, id_sala,
           ROW_NUMBER() OVER (PARTITION BY id_sala ORDER BY fila, numero) AS pos
    FROM asientos
)
INSERT INTO boletas (id_venta, id_funcion, id_asiento)
SELECT p.id_venta, p.id_funcion, s.id_asiento
FROM pedidas p
JOIN sillas s ON s.id_sala = p.id_sala AND s.pos = p.pos;

-- Verifica que todas las ventas pagadas quedaron con sus sillas.
DO $$
DECLARE
    v_boletas BIGINT;
    v_esperadas BIGINT;
BEGIN
    SELECT COUNT(*) INTO v_boletas FROM boletas;
    SELECT COALESCE(SUM(cantidad), 0) INTO v_esperadas FROM ventas WHERE estado = 'Pagada';
    IF v_boletas <> v_esperadas THEN
        RAISE EXCEPTION 'Migración: se crearon % boletas pero las ventas pagadas suman % (alguna función supera la capacidad de su sala)',
            v_boletas, v_esperadas;
    END IF;
END;
$$;


-- ---------------------------------------------------------------------
-- 5. TRIGGERS
-- ---------------------------------------------------------------------

-- 5.1 BOLETAS: coherencia de cada boleta (antes de insertar o modificar)
-- Regla: la boleta pertenece a una venta pagada, la función de la boleta es la
-- de la venta, la silla está en la sala donde se proyecta la función, la silla
-- no está bloqueada y la venta no recibe más boletas que su cantidad.
-- Una FK solo dice que la silla existe; no sabe si está en la sala de esa función.
CREATE OR REPLACE FUNCTION fn_boletas_validar()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_venta          ventas%ROWTYPE;
    v_sala_funcion   funciones.id_sala%TYPE;
    v_sala_asiento   asientos.id_sala%TYPE;
    v_estado_asiento asientos.estado%TYPE;
    v_validas        INTEGER;
BEGIN
    -- Anular una boleta siempre se permite.
    IF NEW.estado = 'Anulada' THEN
        RETURN NEW;
    END IF;

    -- Se bloquea la venta para que dos boletas simultáneas no se pasen del total.
    SELECT * INTO v_venta FROM ventas WHERE id_venta = NEW.id_venta FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La venta % no existe', NEW.id_venta;
    END IF;

    IF v_venta.estado <> 'Pagada' THEN
        RAISE EXCEPTION 'La venta % está %; solo una venta pagada puede tener boletas',
            NEW.id_venta, v_venta.estado;
    END IF;

    IF v_venta.id_funcion <> NEW.id_funcion THEN
        RAISE EXCEPTION 'La boleta es para la función % pero la venta % es de la función %',
            NEW.id_funcion, NEW.id_venta, v_venta.id_funcion;
    END IF;

    SELECT id_sala INTO v_sala_funcion FROM funciones WHERE id_funcion = NEW.id_funcion;

    SELECT id_sala, estado INTO v_sala_asiento, v_estado_asiento
    FROM asientos
    WHERE id_asiento = NEW.id_asiento;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La silla % no existe', NEW.id_asiento;
    END IF;

    IF v_sala_asiento <> v_sala_funcion THEN
        RAISE EXCEPTION 'La silla % es de la sala % pero la función % se proyecta en la sala %',
            NEW.id_asiento, v_sala_asiento, NEW.id_funcion, v_sala_funcion;
    END IF;

    IF v_estado_asiento <> 'Activo' THEN
        RAISE EXCEPTION 'La silla % está %; no se puede vender', NEW.id_asiento, v_estado_asiento;
    END IF;

    SELECT COUNT(*) INTO v_validas
    FROM boletas
    WHERE id_venta = NEW.id_venta
      AND estado = 'Valida'
      AND id_boleta <> NEW.id_boleta;

    IF v_validas + 1 > v_venta.cantidad THEN
        RAISE EXCEPTION 'La venta % es de % boletas y ya tiene todas sus sillas asignadas',
            NEW.id_venta, v_venta.cantidad;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_boletas_validar
BEFORE INSERT OR UPDATE OF id_venta, id_funcion, id_asiento, estado
ON boletas
FOR EACH ROW
EXECUTE FUNCTION fn_boletas_validar();


-- 5.2 VENTAS y BOLETAS: el número de boletas debe ser igual a ventas.cantidad
-- Regla: toda venta pagada tiene exactamente `cantidad` boletas válidas.
-- Es diferido (DEFERRABLE INITIALLY DEFERRED) porque la venta se inserta primero
-- y sus boletas después; si al hacer COMMIT no cuadra, se revierte todo.
CREATE OR REPLACE FUNCTION fn_verificar_boletas_venta(p_id_venta INTEGER)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado   ventas.estado%TYPE;
    v_cantidad ventas.cantidad%TYPE;
    v_validas  INTEGER;
BEGIN
    SELECT estado, cantidad INTO v_estado, v_cantidad
    FROM ventas
    WHERE id_venta = p_id_venta;

    IF NOT FOUND OR v_estado <> 'Pagada' THEN
        RETURN;
    END IF;

    SELECT COUNT(*) INTO v_validas
    FROM boletas
    WHERE id_venta = p_id_venta AND estado = 'Valida';

    IF v_validas <> v_cantidad THEN
        RAISE EXCEPTION 'La venta % es de % boletas pero tiene % sillas asignadas',
            p_id_venta, v_cantidad, v_validas;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION fn_ventas_verificar_boletas()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM fn_verificar_boletas_venta(NEW.id_venta);
    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION fn_boletas_verificar_venta()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM fn_verificar_boletas_venta(OLD.id_venta);
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM fn_verificar_boletas_venta(NEW.id_venta);
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_ventas_verificar_boletas ON ventas;
CREATE CONSTRAINT TRIGGER trg_ventas_verificar_boletas
AFTER INSERT OR UPDATE OF cantidad, estado
ON ventas
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION fn_ventas_verificar_boletas();

DROP TRIGGER IF EXISTS trg_boletas_verificar_venta ON boletas;
CREATE CONSTRAINT TRIGGER trg_boletas_verificar_venta
AFTER INSERT OR UPDATE OR DELETE
ON boletas
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION fn_boletas_verificar_venta();


-- 5.3 VENTAS: al anular una venta se liberan sus sillas
-- Las boletas pasan a 'Anulada' (queda el historial) y, como el índice único
-- solo mira las 'Valida', la silla vuelve a poder venderse.
-- Funciona también cuando sp_cancelar_funcion anula las ventas de una función.
CREATE OR REPLACE FUNCTION fn_ventas_liberar_boletas()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE boletas
    SET estado = 'Anulada'
    WHERE id_venta = NEW.id_venta
      AND estado = 'Valida';
    RETURN NULL;
END;
$$;

CREATE OR REPLACE TRIGGER trg_ventas_liberar_boletas
AFTER UPDATE OF estado
ON ventas
FOR EACH ROW
WHEN (OLD.estado <> 'Anulada' AND NEW.estado = 'Anulada')
EXECUTE FUNCTION fn_ventas_liberar_boletas();


-- 5.4 FUNCIONES: máquina de estados
-- Transiciones válidas:
--   Programada -> En curso | Finalizada | Cancelada
--   En curso   -> Finalizada
--   Finalizada y Cancelada son finales.
-- Compatible con sp_mantenimiento_diario y sp_cancelar_funcion.
CREATE OR REPLACE FUNCTION fn_funciones_validar_estado()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.estado = NEW.estado THEN
        RETURN NEW;
    END IF;

    IF (OLD.estado, NEW.estado) IN (
        ('Programada', 'En curso'),
        ('Programada', 'Finalizada'),
        ('Programada', 'Cancelada'),
        ('En curso',   'Finalizada')
    ) THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'Transición de estado no permitida en la función %: de % a %',
        OLD.id_funcion, OLD.estado, NEW.estado;
END;
$$;

CREATE OR REPLACE TRIGGER trg_funciones_estado
BEFORE UPDATE OF estado
ON funciones
FOR EACH ROW
EXECUTE FUNCTION fn_funciones_validar_estado();


-- 5.5 VENTAS: una venta anulada no se reactiva
-- Pagada -> Anulada es la única transición. Reactivar una venta anulada
-- duplicaría puntos de fidelización y reembolsos ya entregados.
CREATE OR REPLACE FUNCTION fn_ventas_validar_estado()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.estado = 'Anulada' AND NEW.estado <> 'Anulada' THEN
        RAISE EXCEPTION 'La venta % está anulada y no se puede reactivar; registre una venta nueva',
            OLD.id_venta;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_ventas_estado
BEFORE UPDATE OF estado
ON ventas
FOR EACH ROW
EXECUTE FUNCTION fn_ventas_validar_estado();


-- ---------------------------------------------------------------------
-- 6. VISTA para el mapa de sillas
-- Una fila por silla de la sala de cada función no cancelada; `ocupada` indica
-- si la silla tiene una boleta válida para esa función.
-- ---------------------------------------------------------------------
CREATE VIEW v_estado_asientos AS
SELECT f.id_funcion,
       a.id_asiento,
       a.fila,
       a.numero,
       a.tipo,
       a.estado AS estado_silla,
       (b.id_boleta IS NOT NULL) AS ocupada
FROM funciones f
JOIN asientos a ON a.id_sala = f.id_sala
LEFT JOIN boletas b ON b.id_funcion = f.id_funcion
                   AND b.id_asiento = a.id_asiento
                   AND b.estado = 'Valida'
WHERE f.estado <> 'Cancelada';

COMMENT ON VIEW v_estado_asientos IS 'Mapa de sillas por funcion: ocupada = tiene boleta valida';


-- ---------------------------------------------------------------------
-- 7. PRUEBAS: casos que deben bloquearse y casos que deben pasar
-- Cada caso se deshace al terminar y no deja datos en la base.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION pruebas_migracion()
RETURNS TABLE (trigger_probado TEXT, caso TEXT, esperado TEXT, resultado TEXT)
LANGUAGE plpgsql
AS $$
DECLARE
    v_func      INTEGER;    -- función programada, con sillas libres
    v_sala      INTEGER;
    v_otra_func INTEGER;    -- otra función programada, para el caso de función distinta
    v_espec     INTEGER;    -- espectador adulto
    v_tipo      INTEGER;    -- tipo de boleta activo
    v_staff     INTEGER;    -- taquillero activo
    v_sillas    INTEGER[];  -- 3 sillas libres de la sala de v_func
    v_silla_otra_sala INTEGER;
    v_venta1    INTEGER;
    v_venta2    INTEGER;
    v_nueva     INTEGER;
    v_n         INTEGER;
BEGIN
    SELECT f.id_funcion, f.id_sala INTO v_func, v_sala
    FROM funciones f
    WHERE f.estado = 'Programada' AND f.fecha_hora_inicio > NOW()
    ORDER BY f.id_funcion LIMIT 1;

    SELECT f.id_funcion INTO v_otra_func
    FROM funciones f
    WHERE f.estado = 'Programada' AND f.fecha_hora_inicio > NOW() AND f.id_funcion <> v_func
    ORDER BY f.id_funcion LIMIT 1;

    SELECT id_espectador INTO v_espec FROM espectadores
    WHERE fecha_nacimiento < CURRENT_DATE - INTERVAL '25 years' ORDER BY id_espectador LIMIT 1;

    SELECT id_tipo_boleta INTO v_tipo FROM tipos_boleta WHERE activo ORDER BY id_tipo_boleta LIMIT 1;

    SELECT id_staff INTO v_staff FROM staff
    WHERE cargo = 'Taquillero' AND estado = 'Activo' ORDER BY id_staff LIMIT 1;

    SELECT ARRAY_AGG(id_asiento) INTO v_sillas FROM (
        SELECT a.id_asiento
        FROM asientos a
        WHERE a.id_sala = v_sala AND a.estado = 'Activo'
          AND NOT EXISTS (SELECT 1 FROM boletas b
                          WHERE b.id_funcion = v_func AND b.id_asiento = a.id_asiento AND b.estado = 'Valida')
        ORDER BY a.id_asiento DESC LIMIT 3
    ) t;

    SELECT id_asiento INTO v_silla_otra_sala FROM asientos WHERE id_sala <> v_sala ORDER BY id_asiento LIMIT 1;

    -- ===== 1. Boletas: caso válido =====
    trigger_probado := '1 boletas'; caso := 'Venta de 2 boletas con 2 sillas de la sala'; esperado := 'PERMITIDO';
    BEGIN
        INSERT INTO ventas (id_espectador, id_funcion, id_tipo_boleta, id_staff, cantidad, canal_venta, metodo_pago)
        VALUES (v_espec, v_func, v_tipo, v_staff, 2, 'Taquilla', 'Tarjeta') RETURNING id_venta INTO v_nueva;
        INSERT INTO boletas (id_venta, id_funcion, id_asiento) VALUES (v_nueva, v_func, v_sillas[1]), (v_nueva, v_func, v_sillas[2]);
        SET CONSTRAINTS ALL IMMEDIATE;
        resultado := 'PERMITIDO';
        RAISE EXCEPTION 'fin_caso';
    EXCEPTION WHEN OTHERS THEN
        IF SQLERRM <> 'fin_caso' THEN resultado := 'BLOQUEADO: ' || SQLERRM; END IF;
    END;
    RETURN NEXT;

    -- ===== 2. Misma silla vendida dos veces =====
    trigger_probado := '1 boletas'; caso := 'Misma silla vendida dos veces en la misma función'; esperado := 'BLOQUEADO';
    BEGIN
        INSERT INTO ventas (id_espectador, id_funcion, id_tipo_boleta, id_staff, cantidad, canal_venta, metodo_pago)
        VALUES (v_espec, v_func, v_tipo, v_staff, 1, 'Taquilla', 'Tarjeta') RETURNING id_venta INTO v_venta1;
        INSERT INTO ventas (id_espectador, id_funcion, id_tipo_boleta, id_staff, cantidad, canal_venta, metodo_pago)
        VALUES (v_espec, v_func, v_tipo, v_staff, 1, 'Taquilla', 'Tarjeta') RETURNING id_venta INTO v_venta2;
        INSERT INTO boletas (id_venta, id_funcion, id_asiento) VALUES (v_venta1, v_func, v_sillas[1]);
        INSERT INTO boletas (id_venta, id_funcion, id_asiento) VALUES (v_venta2, v_func, v_sillas[1]);
        resultado := 'PERMITIDO';
        RAISE EXCEPTION 'fin_caso';
    EXCEPTION WHEN OTHERS THEN
        IF SQLERRM <> 'fin_caso' THEN resultado := 'BLOQUEADO: ' || SQLERRM; END IF;
    END;
    RETURN NEXT;

    -- ===== 3. Silla de otra sala =====
    trigger_probado := '1 boletas'; caso := 'Silla que pertenece a otra sala'; esperado := 'BLOQUEADO';
    BEGIN
        INSERT INTO ventas (id_espectador, id_funcion, id_tipo_boleta, id_staff, cantidad, canal_venta, metodo_pago)
        VALUES (v_espec, v_func, v_tipo, v_staff, 1, 'Taquilla', 'Tarjeta') RETURNING id_venta INTO v_nueva;
        INSERT INTO boletas (id_venta, id_funcion, id_asiento) VALUES (v_nueva, v_func, v_silla_otra_sala);
        resultado := 'PERMITIDO';
        RAISE EXCEPTION 'fin_caso';
    EXCEPTION WHEN OTHERS THEN
        IF SQLERRM <> 'fin_caso' THEN resultado := 'BLOQUEADO: ' || SQLERRM; END IF;
    END;
    RETURN NEXT;

    -- ===== 4. Silla bloqueada =====
    trigger_probado := '1 boletas'; caso := 'Silla bloqueada (dañada)'; esperado := 'BLOQUEADO';
    BEGIN
        UPDATE asientos SET estado = 'Bloqueado' WHERE id_asiento = v_sillas[3];
        INSERT INTO ventas (id_espectador, id_funcion, id_tipo_boleta, id_staff, cantidad, canal_venta, metodo_pago)
        VALUES (v_espec, v_func, v_tipo, v_staff, 1, 'Taquilla', 'Tarjeta') RETURNING id_venta INTO v_nueva;
        INSERT INTO boletas (id_venta, id_funcion, id_asiento) VALUES (v_nueva, v_func, v_sillas[3]);
        resultado := 'PERMITIDO';
        RAISE EXCEPTION 'fin_caso';
    EXCEPTION WHEN OTHERS THEN
        IF SQLERRM <> 'fin_caso' THEN resultado := 'BLOQUEADO: ' || SQLERRM; END IF;
    END;
    RETURN NEXT;

    -- ===== 5. Boleta de una función distinta a la de la venta =====
    trigger_probado := '1 boletas'; caso := 'Boleta de otra función distinta a la de la venta'; esperado := 'BLOQUEADO';
    BEGIN
        INSERT INTO ventas (id_espectador, id_funcion, id_tipo_boleta, id_staff, cantidad, canal_venta, metodo_pago)
        VALUES (v_espec, v_func, v_tipo, v_staff, 1, 'Taquilla', 'Tarjeta') RETURNING id_venta INTO v_nueva;
        INSERT INTO boletas (id_venta, id_funcion, id_asiento) VALUES (v_nueva, v_otra_func, v_sillas[1]);
        resultado := 'PERMITIDO';
        RAISE EXCEPTION 'fin_caso';
    EXCEPTION WHEN OTHERS THEN
        IF SQLERRM <> 'fin_caso' THEN resultado := 'BLOQUEADO: ' || SQLERRM; END IF;
    END;
    RETURN NEXT;

    -- ===== 6. Más boletas que la cantidad =====
    trigger_probado := '1 boletas'; caso := 'Venta de 1 boleta con 2 sillas asignadas'; esperado := 'BLOQUEADO';
    BEGIN
        INSERT INTO ventas (id_espectador, id_funcion, id_tipo_boleta, id_staff, cantidad, canal_venta, metodo_pago)
        VALUES (v_espec, v_func, v_tipo, v_staff, 1, 'Taquilla', 'Tarjeta') RETURNING id_venta INTO v_nueva;
        INSERT INTO boletas (id_venta, id_funcion, id_asiento) VALUES (v_nueva, v_func, v_sillas[1]);
        INSERT INTO boletas (id_venta, id_funcion, id_asiento) VALUES (v_nueva, v_func, v_sillas[2]);
        resultado := 'PERMITIDO';
        RAISE EXCEPTION 'fin_caso';
    EXCEPTION WHEN OTHERS THEN
        IF SQLERRM <> 'fin_caso' THEN resultado := 'BLOQUEADO: ' || SQLERRM; END IF;
    END;
    RETURN NEXT;

    -- ===== 7. Menos boletas que la cantidad (trigger diferido) =====
    trigger_probado := '2 cantidad = boletas'; caso := 'Venta de 3 boletas con solo 2 sillas (al confirmar)'; esperado := 'BLOQUEADO';
    BEGIN
